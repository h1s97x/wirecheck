mod trust;

use anyhow::{bail, Context, Result};
use clap::{Parser, Subcommand};
use std::fs;
use std::io::IsTerminal;
use std::path::{Path, PathBuf};
use wirecheck_builtins::{
    action_descriptors, find_action, probe_descriptors, BuiltinProbes, DisabledExecutor,
};
use wirecheck_core::plan::{apply_plan, build_plan};
use wirecheck_core::{validate, Outcome, RuleSet, Severity};
use wirecheck_report::render::{render_json, write_reports};

const TEMPLATE: &str = r#"# SPDX-License-Identifier: MIT
# wirecheck starter rule set. Edit the probes below for your environment.
# Example addresses use example.com and RFC 5737 documentation ranges.

version = 1
name = "my-network"
description = "Starter checks generated by `wirecheck init`."

[defaults]
timeout = "2s"
retries = 1
concurrency = 4

[redact]
ip = "mask"
user = "hash"
mac = "mask"

[reports]
formats = ["json", "html", "sarif"]
output_dir = "./reports"

[[probes]]
id = "local_tcp"
type = "tcp"
expect = { status = "refused" }

[probes.with]
host = "127.0.0.1"
port = 1

# More kinds: dns, http, icmp, proxy, interface, traceroute, captive_portal.
# Run `wirecheck list-probes` for the full registry.
"#;

#[derive(Debug, Parser)]
#[command(
    name = "wirecheck",
    version,
    about = "Declarative network health checks, with evidence you can share",
    long_about = None
)]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Debug, Subcommand)]
enum Command {
    /// Generate a commented starter rule set
    Init {
        /// Output path
        #[arg(
            short,
            long,
            default_value = "wirecheck.rules.toml",
            value_name = "FILE"
        )]
        output: PathBuf,
    },
    /// Register a rule set's SHA-256 fingerprint as trusted
    Trust {
        /// Path to a *.rules.toml file
        #[arg(short, long, value_name = "FILE")]
        rules: PathBuf,
    },
    /// Statically validate a rule set. Never touches the network.
    Validate {
        /// Path to a *.rules.toml file
        #[arg(short, long, value_name = "FILE")]
        rules: PathBuf,
        /// Emit diagnostics as JSON, for CI consumption
        #[arg(long)]
        json: bool,
    },
    /// Execute a rule set and write reports (read-only unless --apply is given)
    Run {
        /// Path to a *.rules.toml file
        #[arg(short, long, value_name = "FILE")]
        rules: PathBuf,
        /// Override [reports].output_dir
        #[arg(long, value_name = "DIR")]
        output_dir: Option<PathBuf>,
        /// Override [reports].formats (repeatable: json, html, sarif)
        #[arg(long = "format", value_name = "FORMAT")]
        formats: Vec<String>,
        /// Also print the JSON report to stdout
        #[arg(long)]
        stdout: bool,
        /// Apply the remediation plan (requires --yes)
        #[arg(long)]
        apply: bool,
        /// Confirm --apply non-interactively
        #[arg(long)]
        yes: bool,
        /// Require the rule set fingerprint in .wirecheck/trusted.txt
        #[arg(long = "trust")]
        require_trust: bool,
    },
    /// List built-in probe kinds and their implementation status
    ListProbes,
    /// Show metadata for a remediation action ID
    Explain {
        #[arg(value_name = "ACTION_ID")]
        action: String,
    },
}

fn main() {
    let cli = Cli::parse();
    let code = match run(cli) {
        Ok(code) => code,
        Err(error) => {
            eprintln!("error: {error:#}");
            2
        }
    };
    std::process::exit(code);
}

fn run(cli: Cli) -> Result<i32> {
    match cli.command {
        Command::Init { output } => init_command(&output),
        Command::Trust { rules } => trust_command(&rules),
        Command::Validate { rules, json } => validate_command(&rules, json),
        Command::Run {
            rules,
            output_dir,
            formats,
            stdout,
            apply,
            yes,
            require_trust,
        } => run_command(
            &rules,
            output_dir.as_deref(),
            &formats,
            stdout,
            apply,
            yes,
            require_trust,
        ),
        Command::ListProbes => {
            let implemented = probe_descriptors()
                .iter()
                .filter(|probe| probe.implemented)
                .count();
            println!("probe kinds (M3: {implemented} implemented)");
            for probe in probe_descriptors() {
                let status = if probe.implemented {
                    "implemented"
                } else {
                    "planned"
                };
                let elevated = if probe.requires_elevation {
                    ", elevation"
                } else {
                    ""
                };
                println!(
                    "  {:<16} [{}{}] {}",
                    probe.id, status, elevated, probe.summary
                );
            }
            Ok(0)
        }
        Command::Explain { action } => match find_action(&action) {
            Some(descriptor) => {
                println!("action    : {}", descriptor.id);
                println!("summary   : {}", descriptor.summary);
                println!("kind      : {:?}", descriptor.kind);
                println!("elevation : {}", descriptor.requires_elevation);
                Ok(0)
            }
            None => {
                eprintln!("unknown action id `{action}`");
                let known: Vec<&str> = action_descriptors().iter().map(|a| a.id).collect();
                eprintln!("known ids : {}", known.join(", "));
                Ok(2)
            }
        },
    }
}

fn init_command(output: &Path) -> Result<i32> {
    if output.exists() {
        bail!("`{}` already exists; choose another path", output.display());
    }
    if let Some(parent) = output.parent().filter(|path| !path.as_os_str().is_empty()) {
        fs::create_dir_all(parent)?;
    }
    fs::write(output, TEMPLATE)?;
    println!("created : {}", output.display());
    println!("next    : wirecheck validate --rules {}", output.display());
    println!("          wirecheck trust --rules {}", output.display());
    Ok(0)
}

fn trust_command(rules: &Path) -> Result<i32> {
    let text = fs::read_to_string(rules)
        .with_context(|| format!("cannot read rule set `{}`", rules.display()))?;
    let digest = trust::trust(Path::new("."), rules, &text)?;
    println!("trusted : {}", rules.display());
    println!("sha256  : {digest}");
    Ok(0)
}

fn run_command(
    path: &Path,
    output_dir: Option<&Path>,
    overrides: &[String],
    to_stdout: bool,
    apply: bool,
    yes: bool,
    require_trust: bool,
) -> Result<i32> {
    let text = fs::read_to_string(path)
        .with_context(|| format!("cannot read rule set `{}`", path.display()))?;
    if require_trust && !trust::is_trusted(Path::new("."), path, &text)? {
        bail!(
            "rule set is not trusted; run `wirecheck trust --rules {}` first",
            path.display()
        );
    }
    let rules = RuleSet::from_toml(&text).context("invalid rule set")?;
    let validation = validate(&rules);
    if !validation.is_ok() {
        // Reuse the existing printer so all diagnostics are shown in one pass.
        return validate_command(path, false);
    }

    let report = wirecheck_core::runner::run(&rules, &BuiltinProbes);
    let formats: Vec<String> = if overrides.is_empty() {
        rules.reports.formats.clone()
    } else {
        overrides.to_vec()
    };
    let directory = output_dir
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(&rules.reports.output_dir));
    let written = write_reports(&report, &rules.redact, &formats, &directory)?;

    if to_stdout {
        println!("{}", render_json(&report, &rules.redact)?);
    }
    println!("rule set : {}", report.rule_set);
    println!("clock    : {}", report.generated_at);
    for finding in &report.findings {
        println!(
            "[{}] {}: {}",
            outcome_label(finding.outcome),
            finding.probe_id,
            finding.message
        );
    }
    for file in &written {
        println!("report   : {}", file.display());
    }

    let plan = build_plan(&rules, &report);
    if apply {
        if !yes {
            bail!("--apply requires --yes; plans are dry-run by default");
        }
        if plan.requires_confirm() && !std::io::stdin().is_terminal() {
            bail!("a remediation has needs_confirm = true; an interactive TTY is required");
        }
        // Elevation is handled centrally: this build refuses rather than
        // silently attempting a privileged system change.
        let needs_elevation = plan.actions.iter().any(|action| {
            action_descriptors().iter().any(|descriptor| {
                descriptor.id == action.action.as_str() && descriptor.requires_elevation
            })
        });
        if needs_elevation {
            bail!("a planned action requires elevation; this build does not perform privilege escalation");
        }
        fs::create_dir_all(&directory)?;
        // No host-mutating adapter ships; every action is refused and recorded.
        let audit = apply_plan(&plan, &DisabledExecutor);
        let audit_path = directory.join("audit.json");
        fs::write(&audit_path, serde_json::to_string_pretty(&audit)?)?;
        for result in &audit.results {
            println!(
                "[{}] {}: {}",
                result.status, result.remediation_id, result.detail
            );
        }
        println!("audit    : {}", audit_path.display());
    } else if plan.actions.is_empty() {
        println!("plan     : no remediation suggested (dry-run)");
    } else {
        println!(
            "plan     : {} action(s), dry-run, nothing applied",
            plan.actions.len()
        );
        for action in &plan.actions {
            println!(
                "  [{}] {}: {} needs_confirm={}",
                action.risk, action.remediation_id, action.action, action.needs_confirm
            );
        }
    }
    Ok(report.exit_code())
}

fn outcome_label(outcome: Outcome) -> &'static str {
    match outcome {
        Outcome::Pass => "pass",
        Outcome::Fail => "fail",
        Outcome::Warn => "warn",
        Outcome::Skipped => "skipped",
        Outcome::Error => "error",
    }
}

fn validate_command(path: &Path, json: bool) -> Result<i32> {
    let text = fs::read_to_string(path)
        .with_context(|| format!("cannot read rule set `{}`", path.display()))?;
    let rules = RuleSet::from_toml(&text).context("invalid rule set")?;
    let report = validate(&rules);

    if json {
        println!("{}", serde_json::to_string_pretty(&report)?);
        return Ok(report.exit_code());
    }

    println!("rule set : {}", report.rule_set);
    println!("probes   : {}", report.probe_count);
    println!("remedies : {}", report.remediation_count);
    println!();
    if report.diagnostics.is_empty() {
        println!("OK: no diagnostics.");
    } else {
        for diagnostic in &report.diagnostics {
            println!(
                "[{}] {} {} :: {}",
                severity_label(diagnostic.severity),
                diagnostic.code,
                diagnostic.path,
                diagnostic.message
            );
        }
        println!();
        println!(
            "{} error(s), {} warning(s)",
            report.error_count(),
            report.warning_count()
        );
    }
    println!(
        "validation {}",
        if report.is_ok() { "passed" } else { "failed" }
    );
    Ok(report.exit_code())
}

fn severity_label(severity: Severity) -> &'static str {
    match severity {
        Severity::Error => "error",
        Severity::Warning => "warning",
    }
}
